using System.Linq;
using System.Numerics;
using Content.Client._Starlight.UserInterface.Controls;
using Content.Client.UserInterface.Controls;
using Content.Shared._Starlight.CCVar;
using Robust.Client.AutoGenerated;
using Robust.Client.Input;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Configuration;
using Robust.Shared.Timing;

namespace Content.Client.UserInterface.Systems.MenuBar.Widgets
{
    [GenerateTypedNameReferences]
    public sealed partial class GameTopMenuBar : UIWidget
    {
        #region Starlight
        [Dependency] private readonly IConfigurationManager _cfg = default!;
        [Dependency] private readonly IInputManager _input = default!;

        public static readonly BarLayoutEntry[] LayoutEntries = new[]
        {
            new BarLayoutEntry("EscapeButton", "game-hud-open-escape-menu-button-tooltip"),
            new BarLayoutEntry("GuidebookButton", "game-hud-open-guide-menu-button-tooltip"),
            new BarLayoutEntry("CharacterButton", "game-hud-open-character-menu-button-tooltip"),
            new BarLayoutEntry("EmotesButton", "game-hud-open-emotes-menu-button-tooltip"),
            new BarLayoutEntry("CraftingButton", "game-hud-open-crafting-menu-button-tooltip"),
            new BarLayoutEntry("ActionButton", "game-hud-open-actions-menu-button-tooltip"),
            new BarLayoutEntry("LanguageButton", "ui-options-function-open-language-menu"),
            new BarLayoutEntry("AdminButton", "game-hud-open-admin-menu-button-tooltip"),
            new BarLayoutEntry("AHelpButton", "ui-options-function-open-a-help"),
            new BarLayoutEntry("SandboxButton", "game-hud-open-sandbox-menu-button-tooltip"),
        };

        private string _keyHints = "Hold";
        private readonly List<MenuButton> _buttons = new();
        #endregion

        public GameTopMenuBar()
        {
            RobustXamlLoader.Load(this);
            IoCManager.InjectDependencies(this); // Starlight

            // Starlight-start
            _buttons.AddRange(Bar.Children.OfType<MenuButton>());
            foreach (var button in _buttons)
            {
                button.IconScale = new Vector2(0.45f, 0.45f);
                button.ShowKey = false;
            }

            Bar.Setup();
            _cfg.OnValueChanged(StarlightCCVars.MenuBarLayout, OnMenuBarLayoutChanged, true);
            _cfg.OnValueChanged(StarlightCCVars.MenuBarKeyHints, OnMenuBarKeyHintsChanged, true);
            // Starlight-end
        }

        #region Starlight
        private void OnMenuBarLayoutChanged(string layout)
            => Bar.SetPlacements(BarLayout.Parse(layout));

        private void OnMenuBarKeyHintsChanged(string mode)
            => _keyHints = mode;

        protected override void ExitedTree()
        {
            base.ExitedTree();
            _cfg.UnsubValueChanged(StarlightCCVars.MenuBarLayout, OnMenuBarLayoutChanged);
            _cfg.UnsubValueChanged(StarlightCCVars.MenuBarKeyHints, OnMenuBarKeyHintsChanged);
        }

        protected override void FrameUpdate(FrameEventArgs args)
        {
            base.FrameUpdate(args);

            var show = _keyHints switch
            {
                "Always" => true,
                "Hold" => _input.IsKeyDown(Keyboard.Key.Alt),
                _ => false,
            };

            foreach (var button in _buttons)
                button.KeyHint = show;
        }
        #endregion
    }
}

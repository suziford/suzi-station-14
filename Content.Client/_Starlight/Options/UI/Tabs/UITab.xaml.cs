namespace Content.Client._Starlight.Options.UI.Tabs;

[GenerateTypedNameReferences]
public sealed partial class UITab : Control
{
    [Dependency] private readonly IConfigurationManager _cfg = default!;
    [Dependency] private readonly IPrototypeManager _prototypeManager = default!;
    [Dependency] private readonly IEntitySystemManager _entSysMan = default!;

    public UITab()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        var themeEntries = new List<OptionDropDownCVar<string>.ValueOption>();
        foreach (var gear in _prototypeManager.EnumeratePrototypes<HudThemePrototype>().OrderBy(t => t.Order))
        {
            themeEntries.Add(new OptionDropDownCVar<string>.ValueOption(gear.ID, Loc.GetString(gear.Name)));
        }

        var layoutEntries = new List<OptionDropDownCVar<string>.ValueOption>();
        foreach (var layout in Enum.GetValues(typeof(ScreenType)))
        {
            var name = layout.ToString()!;
            layoutEntries.Add(new OptionDropDownCVar<string>.ValueOption(name, Loc.GetString($"ui-options-hud-layout-{name.ToLower()}")));
        }

        Control.AddOption(new OptionStyleThemeCVar(Control, _cfg, ThemePicker));
        Control.AddOption(new OptionAccentCVar(Control, _cfg, AccentPicker));
        Control.AddOption(new OptionCustomAccentCVar(Control, _cfg, AccentPicker));
        Control.AddOptionDropDown(CVars.InterfaceTheme, DropDownHudTheme, themeEntries);
        Control.AddOptionDropDown(CCVars.UILayout, DropDownHudLayout, layoutEntries);
        Control.AddOptionSlider(StarlightCCVars.ChatSeparatedMinWidth, SeparatedChatWidthSlider, 300, 580);

        Control.AddOptionDropDown(StarlightCCVars.MenuBarKeyHints, DropDownMenuBarKeyHints,
            new[]
            {
                new OptionDropDownCVar<string>.ValueOption("Always", Loc.GetString("ui-options-menu-bar-key-hints-always")),
                new OptionDropDownCVar<string>.ValueOption("Hold", Loc.GetString("ui-options-menu-bar-key-hints-hold")),
                new OptionDropDownCVar<string>.ValueOption("Never", Loc.GetString("ui-options-menu-bar-key-hints-never")),
            });
        MenuBarLayoutEditor.SetEntries(GameTopMenuBar.LayoutEntries);
        Control.AddOption(new OptionBarLayoutCVar(Control, _cfg, StarlightCCVars.MenuBarLayout, MenuBarLayoutEditor));
        Control.AddOptionPercentSlider(CCVars.ChatWindowOpacity, ChatWindowOpacitySlider);
        Control.AddOptionDropDown(
            CVars.DisplayUIScale,
            DropDownUIScale,
            new[]
            {
                new OptionDropDownCVar<float>.ValueOption(
                    0f,
                    Loc.GetString("ui-options-scale-auto", ("scale", UserInterfaceManager.DefaultUIScale))),
                new OptionDropDownCVar<float>.ValueOption(0.75f, Loc.GetString("ui-options-scale-75")),
                new OptionDropDownCVar<float>.ValueOption(1.00f, Loc.GetString("ui-options-scale-100")),
                new OptionDropDownCVar<float>.ValueOption(1.25f, Loc.GetString("ui-options-scale-125")),
                new OptionDropDownCVar<float>.ValueOption(1.50f, Loc.GetString("ui-options-scale-150")),
                new OptionDropDownCVar<float>.ValueOption(1.75f, Loc.GetString("ui-options-scale-175")),
                new OptionDropDownCVar<float>.ValueOption(2.00f, Loc.GetString("ui-options-scale-200")),
            });

        // Sights / Crosshairs
        var rangedSightEntries = new List<OptionDropDownCVar<string>.ValueOption>();
        var meleeSightEntries = new List<OptionDropDownCVar<string>.ValueOption>();
        foreach (var sight in _prototypeManager.EnumeratePrototypes<SightPrototype>())
        {
            if (sight.Bolt)
                continue;

            var opt = new OptionDropDownCVar<string>.ValueOption(sight.ID, Loc.GetString(sight.Name));
            if (sight.SightType is SightType.Ranged or SightType.Universal)
                rangedSightEntries.Add(opt);
            if (sight.SightType is SightType.Melee or SightType.Universal)
                meleeSightEntries.Add(opt);
        }

        Control.AddOptionDropDown(StarlightCCVars.RangedSight, DropDownRangedSight, rangedSightEntries);
        Control.AddOptionDropDown(StarlightCCVars.MeleeSight, DropDownMeleeSight, meleeSightEntries);
        Control.AddOptionSlider(StarlightCCVars.RangedSightScale, RangedSightScaleSlider, 10, 100);
        Control.AddOptionSlider(StarlightCCVars.RangedSightOffset, RangedSightOffsetSlider, 0, 100);
        Control.AddOptionCheckBox(StarlightCCVars.RangedSightRotation, RangedSightRotationCheckBox);
        Control.AddOptionCheckBox(StarlightCCVars.MeleeSightRotation, MeleeSightRotationCheckBox);
        Control.AddOptionDropDown(
            StarlightCCVars.HeldItemShowMode,
            DropDownHeldItemShowMode,
            new[]
            {
                new OptionDropDownCVar<int>.ValueOption((int) HeldItemShowMode.Always, Loc.GetString("ui-options-held-item-show-always")),
                new OptionDropDownCVar<int>.ValueOption((int) HeldItemShowMode.CombatModeOnly, Loc.GetString("ui-options-held-item-show-combat")),
                new OptionDropDownCVar<int>.ValueOption((int) HeldItemShowMode.OutsideCombatModeOnly, Loc.GetString("ui-options-held-item-show-outside-combat")),
                new OptionDropDownCVar<int>.ValueOption((int) HeldItemShowMode.Never, Loc.GetString("ui-options-held-item-show-never")),
            });
        Control.AddOptionCheckBox(StarlightCCVars.SightShowBoltIndicator, SightBoltIndicatorCheckBox);
        Control.AddOptionCheckBox(StarlightCCVars.SightShowJamIndicator, SightJamIndicatorCheckBox);
        Control.AddOptionCheckBox(StarlightCCVars.SightShowHeatIndicator, SightHeatIndicatorCheckBox);
        Control.AddOptionColorSlider(StarlightCCVars.SightMainColor, SightMainColorSlider);
        Control.AddOptionColorSlider(StarlightCCVars.SightSecondColor, SightSecondColorSlider);

        SightsOptionsHash.OnTextChanged += OnTextChanged;

        Control.Initialize();
    }

    protected override void EnteredTree()
    {
        base.EnteredTree();
        _cfg.OnValueChanged(StarlightCCVars.RangedSight, OnSightCVarChanged);
        _cfg.OnValueChanged(StarlightCCVars.MeleeSight, OnSightCVarChanged);
        _cfg.OnValueChanged(StarlightCCVars.RangedSightScale, OnSightCVarChanged);
        _cfg.OnValueChanged(StarlightCCVars.RangedSightOffset, OnSightCVarChanged);
        _cfg.OnValueChanged(StarlightCCVars.RangedSightRotation, OnSightCVarChanged);
        _cfg.OnValueChanged(StarlightCCVars.MeleeSightRotation, OnSightCVarChanged);
        _cfg.OnValueChanged(StarlightCCVars.SightMainColor, OnSightCVarChanged);
        _cfg.OnValueChanged(StarlightCCVars.SightSecondColor, OnSightCVarChanged);
        UpdateSightsOptionsHash();
    }

    protected override void ExitedTree()
    {
        base.ExitedTree();
        _cfg.UnsubValueChanged(StarlightCCVars.RangedSight, OnSightCVarChanged);
        _cfg.UnsubValueChanged(StarlightCCVars.MeleeSight, OnSightCVarChanged);
        _cfg.UnsubValueChanged(StarlightCCVars.RangedSightScale, OnSightCVarChanged);
        _cfg.UnsubValueChanged(StarlightCCVars.RangedSightOffset, OnSightCVarChanged);
        _cfg.UnsubValueChanged(StarlightCCVars.RangedSightRotation, OnSightCVarChanged);
        _cfg.UnsubValueChanged(StarlightCCVars.MeleeSightRotation, OnSightCVarChanged);
        _cfg.UnsubValueChanged(StarlightCCVars.SightMainColor, OnSightCVarChanged);
        _cfg.UnsubValueChanged(StarlightCCVars.SightSecondColor, OnSightCVarChanged);
    }

    private void OnSightCVarChanged<T>(T _)
        => UpdateSightsOptionsHash();

    private void UpdateSightsOptionsHash()
    {
        var ranged = _cfg.GetCVar(StarlightCCVars.RangedSight);
        var melee = _cfg.GetCVar(StarlightCCVars.MeleeSight);
        var scale = _cfg.GetCVar(StarlightCCVars.RangedSightScale);
        var offset = _cfg.GetCVar(StarlightCCVars.RangedSightOffset);
        var rotation = _cfg.GetCVar(StarlightCCVars.RangedSightRotation);
        var meleeRotation = _cfg.GetCVar(StarlightCCVars.MeleeSightRotation);
        var main = _cfg.GetCVar(StarlightCCVars.SightMainColor);
        var second = _cfg.GetCVar(StarlightCCVars.SightSecondColor);
        var raw = $"{ranged}\u001F{melee}\u001F{scale}\u001F{offset}\u001F{rotation}\u001F{main}\u001F{second}\u001F{meleeRotation}";
        var bytes = System.Text.Encoding.UTF8.GetBytes(raw);
        var packed = Convert.ToBase64String(bytes);
        SightsOptionsHash.Text = packed;
        SightsOptionsHash.UpdateDraw();

        if (!_entSysMan.TryGetEntitySystem(out SpriteSystem? sprite))
            return;

        var mainColor = Color.FromHex(main);
        var secondColor = Color.FromHex(second);

        if (_prototypeManager.TryIndex(ranged, out SightPrototype? rangedProto) && rangedProto.SightType is (SightType.Ranged or SightType.Universal))
            UpdateSightPreview(sprite, RangedSightPreview, rangedProto, scale, offset, mainColor, secondColor);

        if (_prototypeManager.TryIndex(melee, out SightPrototype? meleeProto) && meleeProto.SightType is (SightType.Melee or SightType.Universal))
            UpdateSightPreview(sprite, MeleeSightPreview, meleeProto, scale, offset, mainColor, secondColor);
    }

    private static void UpdateSightPreview(SpriteSystem sprite, OptionsSightPreview preview, SightPrototype proto, int scale, int offset, Color main, Color second)
    {
        var rsi = sprite.RsiStateLike(proto.Sprite);
        if (!rsi.IsAnimated || rsi.AnimationFrameCount < 3)
        {
            preview.UpdateTexture(sprite.Frame0(proto.Sprite), scale / 100f, offset / 100f, main, second);
            preview.SetBrackets();
            return;
        }

        var bracket1 = rsi.GetFrame(RsiDirection.South, 0);
        var sight = rsi.GetFrame(RsiDirection.South, 1);
        var bracket2 = rsi.GetFrame(RsiDirection.South, 2);
        var bracket3 = rsi.AnimationFrameCount >= 4 ? rsi.GetFrame(RsiDirection.South, 3) : null;
        var bracket4 = rsi.AnimationFrameCount >= 5 ? rsi.GetFrame(RsiDirection.South, 4) : null;
        preview.UpdateTexture(sight, scale / 100f, offset / 100f, main, second);
        preview.SetBrackets(bracket1, bracket2, bracket3, bracket4);
    }

    private void OnTextChanged(LineEdit.LineEditEventArgs args)
    {
        if (args.Text is not { } packed)
            return;
        byte[] bytes;
        try
        {
            bytes = Convert.FromBase64String(packed);
        }
        catch
        {
            return;
        }
        var raw = System.Text.Encoding.UTF8.GetString(bytes);
        var parts = raw.Split('\u001F');

        if (parts.Length is not (7 or 8))
            return;

        if (_prototypeManager.TryIndex(parts[0], out SightPrototype? ranged) && ranged.SightType is (SightType.Ranged or SightType.Universal))
            _cfg.SetCVar(StarlightCCVars.RangedSight, parts[0], true);

        if (_prototypeManager.TryIndex(parts[1], out SightPrototype? melee) && melee.SightType is (SightType.Melee or SightType.Universal))
            _cfg.SetCVar(StarlightCCVars.MeleeSight, parts[1], true);

        if (int.TryParse(parts[2], out var scale))
            _cfg.SetCVar(StarlightCCVars.RangedSightScale, scale, true);
        if (int.TryParse(parts[3], out var offset))
            _cfg.SetCVar(StarlightCCVars.RangedSightOffset, offset, true);

        if (bool.TryParse(parts[4], out var rotation))
            _cfg.SetCVar(StarlightCCVars.RangedSightRotation, rotation, true);

        if (bool.TryParse(parts.Length > 7 ? parts[7] : parts[4], out var meleeRotation))
            _cfg.SetCVar(StarlightCCVars.MeleeSightRotation, meleeRotation, true);

        if (Color.TryFromHex(parts[5], out _))
            _cfg.SetCVar(StarlightCCVars.SightMainColor, parts[5], true);

        if (Color.TryFromHex(parts[6], out _))
            _cfg.SetCVar(StarlightCCVars.SightSecondColor, parts[6], true);
    }
}
